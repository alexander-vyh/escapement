def _read_fragment(root: Path, rel: str) -> str:
    path = root / rel
    return path.read_text(encoding="utf-8").strip()


def _render_fragment(root: Path, rel: str, identity: dict[str, Any]) -> str:
    text = _read_fragment(root, rel)
    if rel != "agent-surfaces/onboarding/shared.md":
        return text
    if MISSION_START in text and MISSION_END in text:
        before, remainder = text.split(MISSION_START, 1)
        _current, after = remainder.split(MISSION_END, 1)
        mission = identity.get("mission", "")
        text = f"{before}{MISSION_START}\n{mission}\n{MISSION_END}{after}"
    if CAPABILITIES_START in text and CAPABILITIES_END in text:
        before, remainder = text.split(CAPABILITIES_START, 1)
        _current, after = remainder.split(CAPABILITIES_END, 1)
        capabilities = "\n".join(
            f"{index}. {capability}"
            for index, capability in enumerate(identity.get("capabilities", ()), start=1)
        )
        text = f"{before}{CAPABILITIES_START}\n{capabilities}\n{CAPABILITIES_END}{after}"
    if ADAPTER_MAPPING_START in text and ADAPTER_MAPPING_END in text:
        before, remainder = text.split(ADAPTER_MAPPING_START, 1)
        _current, after = remainder.split(ADAPTER_MAPPING_END, 1)
        mapping = "\n".join(
            f"- {capability} | {', '.join(tools)}"
            for capability, tools in identity.get("current_adapters", {}).items()
        )
        text = f"{before}{ADAPTER_MAPPING_START}\n{mapping}\n{ADAPTER_MAPPING_END}{after}"
    return text


# hosts.<id>.include_shared_fragments defaults True (codex/claude): their
# rendered document is the host's ONLY delivery channel for the shared
# Escapement workflow text, so it must carry the shared fragments in full.
# Pi sets it False: the Pi host (OMP) auto-loads this repository's AGENTS.md
# natively as repo-rules context on every session, so PI.md — injected a
# second time via before_agent_start — only needs the Pi-specific delta.
# Carrying the shared fragments in both would double every Pi session's
# fixed context cost for text already delivered (escapement-w4sn is the
# same principle applied to Claude's disjoint claude/rules/* channel).
def _render_document(
    root: Path,
    manifest: dict[str, Any],
    identity: dict[str, Any],
    host: str,
) -> str:
    docs = manifest["documents"]
    host_doc = docs["hosts"][host]
    parts = [GENERATED_HEADER, "", f"# {host_doc['title']}", ""]
    if host_doc.get("include_shared_fragments", True):
        for rel in docs["shared_fragments"]:
            parts.append(_render_fragment(root, rel, identity))
            parts.append("")
    for rel in host_doc["fragments"]:
        parts.append(_read_fragment(root, rel))
        parts.append("")
    return "\n".join(parts).rstrip() + "\n"


