def _ready_mcp_servers(manifest: dict[str, Any], host: str) -> list[tuple[dict[str, Any], dict[str, Any]]]:
    return [
        (server, server["hosts"][host])
        for server in manifest.get("mcp_servers", [])
        if server.get("hosts", {}).get(host, {}).get("status") == "ready"
    ]


def _render_mcp_config(manifest: dict[str, Any], host: str) -> str:
    """One MCP launch contract per server; hosts differ only in Serena-style
    `--context` and host-specific options (e.g. Codex startup timeout)."""
    servers: dict[str, Any] = {}
    for server, entry in _ready_mcp_servers(manifest, host):
        args = list(server["args"])
        if entry.get("context"):
            args += ["--context", entry["context"]]
        servers[server["id"]] = {
            "command": server["command"],
            "args": args,
            **entry.get("options", {}),
        }
    return json.dumps({"mcpServers": servers}, indent=2) + "\n"


