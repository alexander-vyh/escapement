def rendered_targets(
    root: Path,
    manifest: dict[str, Any],
    identity: dict[str, Any] | None = None,
) -> dict[Path, str]:
    if identity is None:
        identity = _load_identity(root / DEFAULT_IDENTITY)
    docs = manifest["documents"]["hosts"]
    targets = {
        root / docs["codex"]["target"]: _render_document(root, manifest, identity, "codex"),
        root / docs["claude"]["target"]: _render_document(root, manifest, identity, "claude"),
        root / docs["pi"]["target"]: _render_document(root, manifest, identity, "pi"),
        root / "package.json": _render_pi_package(identity),
        root / PI_PLUGIN_ROOT / "gates.json": _render_pi_gate_inventory(manifest),
        # Every module of the Pi extension: index.ts is the entry package.json
        # names, and it imports its siblings relatively.
        **{
            root / PI_PLUGIN_ROOT / "extensions" / module.name: module.read_text(encoding="utf-8")
            for module in sorted((root / "agent-surfaces" / "hosts" / "pi" / "extensions").glob("*.ts"))
        },
        root / ".codex" / "hooks.json": _render_codex_hooks(manifest),
        root / ".agents" / "plugins" / "marketplace.json": _render_codex_marketplace(),
        root / CODEX_PLUGIN_ROOT / ".codex-plugin" / "plugin.json": _render_codex_plugin_manifest(identity, manifest),
        root / CODEX_PLUGIN_ROOT / "hooks" / "hooks.json": _render_codex_plugin_hooks(
            manifest, _read_json_or_none(root / CODEX_PLUGIN_ROOT / "hooks" / "hooks.json")
        ),
        # Escapement-owned MCP servers, one file per host package.
        root / CODEX_PLUGIN_ROOT / MCP_CONFIG_NAME: _render_mcp_config(manifest, "codex"),
        root / CLAUDE_PLUGIN_ROOT / MCP_CONFIG_NAME: _render_mcp_config(manifest, "claude"),
        root / PI_PLUGIN_ROOT / PI_MCP_CONFIG: _render_mcp_config(manifest, "pi"),
    }

    # Canon-projected surfaces (agent-surfaces/openspec/<op>.md, agent-surfaces/
    # skills/<id>.md) are the single authoring source for ops/skills with a
    # per-host content variance; project them into their host surfaces FIRST so
    # the vendoring loops below vendor the freshly-projected bytes rather than a
    # stale on-disk read of the very file this projection also writes (the
    # canon/host data-flow-inversion this topology avoids: canon is read-only
    # input, .agents/skills/*/SKILL.md, claude/skills/*/SKILL.md, and
    # .claude/commands/opsx/*.md are write-only outputs, never both).
    openspec_surfaces: dict[Path, str] = {}
    for canon_dir in CANON_DIRS:
        openspec_surfaces.update(_openspec_projection_targets(root, canon_dir=Path(canon_dir)))
    targets.update(openspec_surfaces)

    def skill_files(skills_root: Path) -> list[Path]:
        # On-disk skills plus freshly projected ones, so a new canon skill is
        # vendored on its first render instead of drifting until the second.
        found = set(skills_root.glob("*/SKILL.md"))
        found.update(
            path for path in openspec_surfaces
            if path.name == "SKILL.md" and path.parent.parent == skills_root
        )
        return sorted(found)

    for skill_path in skill_files(root / ".agents" / "skills"):
        rel = skill_path.relative_to(root / ".agents")
        content = openspec_surfaces.get(skill_path, None)
        if content is None:
            content = skill_path.read_text(encoding="utf-8")
        targets[root / CODEX_PLUGIN_ROOT / rel] = content
        for sibling in sorted(skill_path.parent.rglob("*")):
            if sibling.is_file() and sibling != skill_path:
                sib_rel = sibling.relative_to(root / ".agents")
                targets[root / CODEX_PLUGIN_ROOT / sib_rel] = sibling.read_text(encoding="utf-8")

    for source in sorted(SHARED_RUNTIME_SUPPORT):
        content = (root / source).read_text(encoding="utf-8")
        targets[root / CODEX_PLUGIN_ROOT / source] = content
        targets[root / CLAUDE_PLUGIN_ROOT / source] = content
        targets[root / PI_PLUGIN_ROOT / source] = content

    hook_sources = _codex_ready_hook_sources(manifest)
    if hook_sources:
        hook_sources.update(SHARED_HOOK_SUPPORT)
    for source in sorted(hook_sources):
        source_path = root / source
        if source_path.exists():
            targets[root / CODEX_PLUGIN_ROOT / source] = source_path.read_text(encoding="utf-8")
    for source in sorted(CODEX_HOOK_SUPPORT):
        source_path = root / source
        if source_path.exists():
            targets[root / CODEX_PLUGIN_ROOT / source] = source_path.read_text(encoding="utf-8")

    # Every Pi gate and every sibling module it imports. gates.json names a
    # gate by path and the dispatcher opens it from the plugin root, so a gate
    # listed but not vendored is a gate that cannot run -- the inventory looks
    # right and the brake is not there.
    for source in sorted(_pi_gate_sources(manifest, root, SHARED_HOOK_SUPPORT)):
        source_path = root / source
        if source_path.exists():
            targets[root / PI_PLUGIN_ROOT / source] = source_path.read_text(encoding="utf-8")

    # --- Claude plugin tree (plugins/escapement-claude) + root marketplace ---
    targets[root / ".claude-plugin" / "marketplace.json"] = _render_claude_marketplace(identity)
    targets[root / CLAUDE_PLUGIN_ROOT / ".claude-plugin" / "plugin.json"] = _render_claude_plugin_manifest(identity)
    targets[root / CLAUDE_PLUGIN_ROOT / "hooks" / "hooks.json"] = _render_claude_plugin_hooks(manifest)

    # Rules, commands and agents for every ready host (tools/host_surfaces.py).
    targets.update(_host_surfaces.render_targets(root, manifest, openspec_surfaces))

    # Vendor Claude skills at the plugin's default location.
    for skill_path in skill_files(root / "claude" / "skills"):
        rel = skill_path.relative_to(root / "claude")
        content = openspec_surfaces.get(skill_path, None)
        if content is None:
            content = skill_path.read_text(encoding="utf-8")
        targets[root / CLAUDE_PLUGIN_ROOT / rel] = content
        if skill_path.parent.is_dir():
            for sibling in sorted(skill_path.parent.rglob("*")):
                if sibling.is_file() and sibling != skill_path:
                    sib_rel = sibling.relative_to(root / "claude")
                    targets[root / CLAUDE_PLUGIN_ROOT / sib_rel] = sibling.read_text(encoding="utf-8")

    # Vendor Claude-ready hook sources into hooks/ (flat) plus the shared
    # _gate_signal helper, so a hook's `from _gate_signal import record` resolves.
    claude_hook_sources = _claude_ready_hook_sources(manifest)
    if claude_hook_sources:
        claude_hook_sources.update(SHARED_HOOK_SUPPORT | CLAUDE_EXTRA_HOOK_SUPPORT)
    for source in sorted(claude_hook_sources):
        # harness/* sources are vendored wholesale into harness/ below, not flat into hooks/.
        if source.startswith("harness/"):
            continue
        source_path = root / source
        if source_path.exists():
            targets[root / CLAUDE_PLUGIN_ROOT / "hooks" / Path(source).name] = source_path.read_text(encoding="utf-8")

    # Bundle the continuation-harness (bin + schemas) so its hooks run from the
    # plugin via ${CLAUDE_PLUGIN_ROOT}/harness/bin. Runtime STATE still resolves to
    # ~/.claude/harness (DEFAULT_HARNESS_ROOT), independent of this read-only code.
    for sub in ("bin", "schemas"):
        src_dir = root / "harness" / sub
        for hpath in sorted(src_dir.glob("*")):
            if hpath.is_file():
                targets[root / CLAUDE_PLUGIN_ROOT / "harness" / sub / hpath.name] = \
                    hpath.read_text(encoding="utf-8")

    return targets


def _is_within(path: Path, parent: Path) -> bool:
    try:
        path.relative_to(parent)
    except ValueError:
        return False
    return True


def _publication_units(root: Path, targets: dict[Path, str]) -> tuple[Path, ...]:
    """Return atomic replacement units for generated files and complete plugin trees."""

    managed_roots = (CODEX_PLUGIN_ROOT, CLAUDE_PLUGIN_ROOT, PI_PLUGIN_ROOT)
    units = {Path(".codex-plugin"), *managed_roots}
    for target in targets:
        relative = target.relative_to(root)
        if not any(_is_within(relative, managed_root) for managed_root in managed_roots):
            units.add(relative)
    return tuple(sorted(units, key=lambda path: (len(path.parts), path.as_posix())))


def _stage_targets(root: Path, targets: dict[Path, str], prepared: Path) -> None:
    """Write the complete next generation without modifying any published surface."""

    for path, content in targets.items():
        staged = prepared / path.relative_to(root)
        staged.parent.mkdir(parents=True, exist_ok=True)
        staged.write_text(content, encoding="utf-8")
        if staged.name == "escapement-worktree" and staged.parent.name == "bin":
            staged.chmod(0o755)


def _remove_published_path(path: Path) -> None:
    if path.is_dir() and not path.is_symlink():
        shutil.rmtree(path)
    elif path.exists() or path.is_symlink():
        path.unlink()


def _publish_staged(root: Path, prepared: Path, backup: Path, units: tuple[Path, ...]) -> None:
    """Publish all staged units transactionally, restoring old state on any failure."""

    states: list[tuple[Path, Path, bool]] = []
    try:
        for relative in units:
            destination = root / relative
            staged = prepared / relative
            saved = backup / relative
            had_existing = destination.exists() or destination.is_symlink()
            if had_existing:
                saved.parent.mkdir(parents=True, exist_ok=True)
                os.replace(destination, saved)
            states.append((destination, saved, had_existing))
            if staged.exists() or staged.is_symlink():
                destination.parent.mkdir(parents=True, exist_ok=True)
                os.replace(staged, destination)
    except OSError as publish_error:
        rollback_errors: list[str] = []
        for destination, saved, had_existing in reversed(states):
            try:
                _remove_published_path(destination)
                if had_existing:
                    destination.parent.mkdir(parents=True, exist_ok=True)
                    os.replace(saved, destination)
            except OSError as rollback_error:
                rollback_errors.append(f"{destination}: {rollback_error}")
        if rollback_errors:
            detail = "; ".join(rollback_errors)
            raise OSError(f"publish failed ({publish_error}); rollback incomplete: {detail}") from publish_error
        raise


def _validate_host_entry(kind: str, item_id: str, host: str, entry: dict[str, Any], errors: list[str]) -> None:
    status = entry.get("status")
    if status not in VALID_STATUSES:
        errors.append(f"{kind} {item_id}: host {host} has invalid status {status!r}")
        return
    if status == "ready":
        if kind == "hook" and not entry.get("fixtures"):
            errors.append(f"hook {item_id}: host {host} ready without fixtures")
        if not entry.get("events") and kind == "hook":
            errors.append(f"hook {item_id}: host {host} ready without events")
    if status in {"partial", "unsupported"} and not entry.get("unsupported_reason"):
        errors.append(f"{kind} {item_id}: host {host} {status} without unsupported_reason")


def _validate_fixture(root: Path, kind: str, item_id: str, host: str, fixture: str, errors: list[str]) -> None:
    path_text, _, selector = fixture.partition("::")
    path = root / path_text
    if kind == "hook" and host == "codex":
        if not selector or path.suffix != ".py":
            errors.append(f"{kind} {item_id}: host {host} Codex hook fixture must be a pytest selector: {fixture}")
        elif "codex" not in selector.lower():
            errors.append(f"{kind} {item_id}: host {host} Codex hook fixture must be Codex-specific: {fixture}")
    if not path.exists():
        errors.append(f"{kind} {item_id}: host {host} fixture does not exist: {fixture}")
        return
    if selector:
        text = path.read_text(encoding="utf-8", errors="replace")
        selector_name = selector.split("[", 1)[0]
        if f"def {selector_name}(" not in text and f"class {selector_name}" not in text:
            errors.append(f"{kind} {item_id}: host {host} fixture selector not found: {fixture}")


def _fixture_matches_hook_source(root: Path, fixture: str, source: str, item_id: str) -> bool:
    path_text, _, _selector = fixture.partition("::")
    fixture_path = root / path_text
    if not fixture_path.is_file():
        return False
    fixture_text = fixture_path.read_text(encoding="utf-8", errors="replace")
    normalized_fixture = fixture_text.lower().replace("-", "_")
    source_stem = Path(source).stem.lower().replace("-", "_")
    hook_id = item_id.lower().replace("-", "_")
    return source_stem in normalized_fixture or hook_id in normalized_fixture


def _frontmatter(text: str) -> dict[str, str] | None:
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return None
    values: dict[str, str] = {}
    for line in lines[1:]:
        if line.strip() == "---":
            return values
        if ":" not in line or line.startswith(" "):
            continue
        key, value = line.split(":", 1)
        values[key.strip()] = value.strip().strip('"')
    return None


CANON_DIRS = ("agent-surfaces/openspec", "agent-surfaces/skills", "agent-surfaces/commands", "agent-surfaces/rules")


def _projected_surfaces(root: Path) -> dict[str, str]:
    """Canon projections by repo-relative path: what a render will write."""
    projected: dict[str, str] = {}
    for canon_dir in CANON_DIRS:
        for path, content in _openspec_projection_targets(root, canon_dir=Path(canon_dir)).items():
            projected[path.relative_to(root).as_posix()] = content
    return projected


def _validate_codex_skill(
    root: Path, skill: dict[str, Any], errors: list[str], projected: dict[str, str]
) -> None:
    item_id = skill.get("id", "<missing>")
    target = skill.get("target")
    if not target:
        errors.append(f"skill {item_id}: missing target")
        return
    # Judge the file on disk; a canon skill not yet rendered is judged by the
    # text the render will write.
    path = root / target
    if path.exists():
        text = path.read_text(encoding="utf-8", errors="replace")
    elif target in projected:
        text = projected[target]
    else:
        errors.append(f"skill {item_id}: target missing: {target}")
        return
    if len(text.strip()) < 200:
        errors.append(f"skill {item_id}: Codex skill is empty or too small")

    frontmatter = _frontmatter(text)
    if frontmatter is None:
        errors.append(f"skill {item_id}: Codex skill missing YAML frontmatter")
    else:
        if frontmatter.get("name") != item_id:
            errors.append(f"skill {item_id}: frontmatter name does not match id")
        if not frontmatter.get("description"):
            errors.append(f"skill {item_id}: frontmatter missing description")

    lowered = text.lower()
    if item_id.startswith("openspec-") and "openspec" not in lowered:
        errors.append(f"skill {item_id}: Codex skill lacks OpenSpec workflow content")
    for token in CODEX_SKILL_FORBIDDEN:
        if token in text:
            errors.append(f"skill {item_id}: Codex skill references unavailable tool token: {token}")
    for token in CODEX_FORBIDDEN:
        if token in text:
            errors.append(f"skill {item_id}: Codex skill contains forbidden Claude-only token: {token}")


def validate_manifest(root: Path, manifest: dict[str, Any]) -> list[str]:
    errors: list[str] = []
    for host in ("codex", "claude", "pi"):
        if host not in manifest.get("documents", {}).get("hosts", {}):
            errors.append(f"documents missing host {host}")

    errors.extend(_validate_pi_adapter(manifest))

    for hook in manifest.get("hooks", []):
        item_id = hook.get("id", "<missing>")
        hosts = hook.get("hosts", {})
        for host in ("codex", "claude"):
            if host not in hosts:
                errors.append(f"hook {item_id}: missing host {host}")
                continue
            _validate_host_entry("hook", item_id, host, hosts[host], errors)
            for fixture in hosts[host].get("fixtures", []):
                _validate_fixture(root, "hook", item_id, host, fixture, errors)
        if "pi" in hosts:
            _validate_host_entry("hook", item_id, "pi", hosts["pi"], errors)
            for fixture in hosts["pi"].get("fixtures", []):
                _validate_fixture(root, "hook", item_id, "pi", fixture, errors)
            _validate_pi_events(root, manifest, hook, errors)
        elif _pi_status(manifest, hook) is None:
            errors.append(f"hook {item_id}: missing host pi ({ALL_HOSTS_POLICY})")
        codex = hosts.get("codex", {})
        if codex.get("status") == "ready":
            source = hook.get("source")
            if source and source != "bd" and Path(source).suffix == ".py":
                fixtures = codex.get("fixtures", [])
                if not any(
                    _fixture_matches_hook_source(root, fixture, source, item_id)
                    for fixture in fixtures
                ):
                    errors.append(f"hook {item_id}: Codex hook fixture must match hook source: {source}")
            for event in codex.get("events", []):
                command = event.get("command", "")
                if "timeout" in event:
                    errors.append(f"hook {item_id}: Codex event must use timeout_seconds, not timeout")
                timeout = event.get("timeout_seconds")
                if timeout is not None:
                    if not isinstance(timeout, int) or timeout <= 0:
                        errors.append(f"hook {item_id}: Codex timeout_seconds must be a positive integer")
                    elif timeout > MAX_CODEX_HOOK_TIMEOUT_SECONDS:
                        errors.append(
                            f"hook {item_id}: Codex timeout_seconds exceeds "
                            f"{MAX_CODEX_HOOK_TIMEOUT_SECONDS}: {timeout}"
                        )
                if "~/.claude" in command:
                    errors.append(f"hook {item_id}: Codex command uses ~/.claude")
                if not command:
                    errors.append(f"hook {item_id}: Codex event missing command")
                source = hook.get("source")
                if source and source != "bd" and not (root / source).exists():
                    errors.append(f"hook {item_id}: source does not exist: {source}")

    projected = _projected_surfaces(root)
    manifest_skill_targets = {skill.get("target") for skill in manifest.get("skills", [])}
    actual_skill_targets = {
        path.relative_to(root).as_posix()
        for path in sorted((root / ".agents" / "skills").glob("*/SKILL.md"))
    } | {
        target for target in projected
        if target.startswith(".agents/skills/") and target.endswith("/SKILL.md")
    }
    missing_from_manifest = actual_skill_targets - manifest_skill_targets
    extra_in_manifest = {target for target in manifest_skill_targets if target} - actual_skill_targets
    for target in sorted(missing_from_manifest):
        errors.append(f"skill target not listed in manifest: {target}")
    for target in sorted(extra_in_manifest):
        errors.append(f"manifest skill target missing from workspace: {target}")

    for skill in manifest.get("skills", []):
        item_id = skill.get("id", "<missing>")
        hosts = skill.get("hosts", {})
        for host in ALL_HOSTS:
            if host not in hosts:
                errors.append(f"skill {item_id}: missing host {host} ({ALL_HOSTS_POLICY})")
                continue
            _validate_host_entry("skill", item_id, host, hosts[host], errors)
            counterpart = hosts[host].get("counterpart")
            if counterpart and not (root / counterpart).exists():
                errors.append(f"skill {item_id}: host {host} counterpart does not exist: {counterpart}")
        if hosts.get("codex", {}).get("status") == "ready":
            _validate_codex_skill(root, skill, errors, projected)
        if hosts.get("pi", {}).get("status") == "ready":
            target = skill.get("target") or ""
            if not any(target.startswith(f"{Path(entry).as_posix()}/") for entry in PI_SKILL_DIRS):
                errors.append(f"skill {item_id}: Pi-ready skill target is outside package pi.skills: {target}")

    for server in manifest.get("mcp_servers", []):
        item_id = server.get("id", "<missing>")
        if not server.get("command") or not isinstance(server.get("args"), list):
            errors.append(f"mcp server {item_id}: missing command or args")
        hosts = server.get("hosts", {})
        for host in ALL_HOSTS:
            if host not in hosts:
                errors.append(f"mcp server {item_id}: missing host {host} ({ALL_HOSTS_POLICY})")
                continue
            _validate_host_entry("mcp server", item_id, host, hosts[host], errors)
            if hosts[host].get("status") == "ready" and not hosts[host].get("fixtures"):
                errors.append(f"mcp server {item_id}: host {host} ready without fixtures")
            for fixture in hosts[host].get("fixtures", []):
                _validate_fixture(root, "mcp server", item_id, host, fixture, errors)

    return errors


def _validate_pi_events(root: Path, manifest: dict[str, Any], hook: dict[str, Any], errors: list[str]) -> None:
    """A Pi event the extension does not translate is a gate that never runs,
    and a Pi gate whose file is absent is a gate the package cannot carry."""
    item_id = hook.get("id", "<missing>")
    entry = hook.get("hosts", {}).get("pi", {})
    adapter = manifest.get("adapters", {}).get("pi", {})
    try:
        tool_targets = set(_pi_tool_targets(adapter))
    except KeyError:
        tool_targets = set()  # validate_adapter reports the broken mapping
    tool_events = (adapter.get("source_event"), adapter.get("post_tool_source_event"))
    whole_events = (
        adapter.get("context_source_event"),
        adapter.get("session_source_event"),
        adapter.get("stop_source_event"),
    )
    for event in entry.get("events", []):
        name, matcher = event.get("event"), event.get("matcher")
        if name in tool_events:
            if matcher not in tool_targets:
                errors.append(f"hook {item_id}: Pi {name} matcher {matcher!r} is not a translated Pi tool")
        elif name not in whole_events:
            errors.append(f"hook {item_id}: Pi event {name!r} is not translated by the Pi adapter")
        timeout = event.get("timeout_seconds")
        if not isinstance(timeout, int) or timeout <= 0:
            errors.append(f"hook {item_id}: Pi event needs a positive integer timeout_seconds")
    source = entry.get("source") or hook.get("source")
    if entry.get("status") == "ready" and source and not (root / source).is_file():
        errors.append(f"hook {item_id}: Pi gate source does not exist, so the Pi package cannot carry it: {source}")


def validate_codex_surfaces(targets: dict[Path, str], manifest: dict[str, Any]) -> list[str]:
    errors: list[str] = []
    codex_text = targets[next(path for path in targets if path.name == "AGENTS.md")]
    codex_hooks = targets[next(path for path in targets if path.as_posix().endswith(".codex/hooks.json"))]
    plugin_hooks = targets[next(path for path in targets if path.as_posix().endswith("plugins/escapement/hooks/hooks.json"))]
    for needle in CODEX_FORBIDDEN:
        if needle in codex_text or needle in codex_hooks or needle in plugin_hooks:
            errors.append(f"Codex surface contains forbidden Claude-only token: {needle}")
    if "${CLAUDE_PLUGIN_ROOT}" in plugin_hooks:
        errors.append("Codex plugin hooks must not use CLAUDE_PLUGIN_ROOT")

    repo_hooks = json.loads(codex_hooks)["hooks"]
    if repo_hooks:
        errors.append(
            "repo-local Codex hooks must be empty because the plugin is the sole hook owner"
        )

    plugin_commands = [
        hook["command"]
        for event_items in json.loads(plugin_hooks)["hooks"].values()
        for item in event_items
        for hook in item["hooks"]
    ]
    if any("bd prime" in command for command in plugin_commands):
        errors.append("Codex hooks must not delegate workflow policy to bd prime")
    if not any("escapement_session_context.py" in command for command in plugin_commands):
        errors.append("Codex plugin hooks must include Escapement-owned session context")
    if not any("gate.py" in command for command in plugin_commands):
        errors.append(
            "Codex plugin hooks must include at least one behavioral gate beyond session context"
        )

    for required in (
        "test_oracle_brief_gate.py",
        "implementation_echo_test_gate.py",
        "oracle_downgrade_warning_gate.py",
    ):
        if not any(required in command for command in plugin_commands):
            errors.append(f"Codex plugin hooks must include {required}")
    return errors


def validate_host_surfaces(root: Path, manifest: dict[str, Any], targets: dict[Path, str]) -> list[str]:
    """Rules, commands and agents obey the all-hosts policy (tools/host_surfaces.py)."""
    return _host_surfaces.validate(
        root, manifest, targets, ALL_HOSTS, ALL_HOSTS_POLICY, _validate_host_entry
    )


def check(root: Path, manifest_path: Path) -> int:
    manifest = _load_manifest(manifest_path)
    identity = _load_identity(root / DEFAULT_IDENTITY)
    targets = rendered_targets(root, manifest, identity)
    errors = validate_manifest(root, manifest)
    errors.extend(validate_identity_surfaces(root, manifest, identity))
    errors.extend(validate_codex_surfaces(targets, manifest))
    errors.extend(validate_host_surfaces(root, manifest, targets))

    for path, expected in targets.items():
        if not path.exists():
            errors.append(f"generated target missing: {path.relative_to(root)}")
            continue
        actual = path.read_text(encoding="utf-8")
        if actual != expected:
            errors.append(f"generated target drift: {path.relative_to(root)}")

    if errors:
        for error in errors:
            print(error, file=sys.stderr)
        return 1
    return 0


def render(root: Path, manifest_path: Path) -> int:
    manifest = _load_manifest(manifest_path)
    identity = _load_identity(root / DEFAULT_IDENTITY)
    errors = validate_manifest(root, manifest)
    errors.extend(validate_canonical_identity(identity))
    errors.extend(validate_support_manifest(manifest))
    if errors:
        for error in errors:
            print(error, file=sys.stderr)
        return 1

    targets = rendered_targets(root, manifest, identity)
    overrides = {path.relative_to(root): content for path, content in targets.items()}
    errors = validate_identity_surfaces(root, manifest, identity, overrides)
    errors.extend(validate_codex_surfaces(targets, manifest))
    errors.extend(validate_host_surfaces(root, manifest, targets))
    if errors:
        for error in errors:
            print(error, file=sys.stderr)
        return 1

    try:
        with tempfile.TemporaryDirectory(prefix=".agent-surface-stage-", dir=root) as temporary:
            transaction = Path(temporary)
            prepared = transaction / "prepared"
            backup = transaction / "backup"
            _stage_targets(root, targets, prepared)
            _publish_staged(root, prepared, backup, _publication_units(root, targets))
    except OSError as error:
        print(f"agent surface publication failed: {error}", file=sys.stderr)
        return 1
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if generated files drift")
    parser.add_argument("--manifest", default=str(DEFAULT_MANIFEST))
    parser.add_argument("--root", default=".")
    args = parser.parse_args(argv)

    root = Path(args.root).resolve()
    manifest_path = Path(args.manifest)
    if not manifest_path.is_absolute():
        manifest_path = root / manifest_path
    if args.check:
        return check(root, manifest_path)
    return render(root, manifest_path)


if __name__ == "__main__":
    raise SystemExit(main())
